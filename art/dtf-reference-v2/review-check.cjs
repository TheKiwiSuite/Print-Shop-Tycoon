const { chromium } = require('playwright');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');
(async () => {
  const browser = await chromium.launch({...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? {executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE} : {}), headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
  const errors=[]; page.on('pageerror',e=>errors.push(String(e)));
  const url=pathToFileURL(path.join(__dirname,'index.html')).href;
  await page.goto(url);
  await page.waitForFunction(()=>[...document.images].every(i=>i.complete && i.naturalWidth>0));
  await page.locator('#next').click();
  if(await page.locator('#angle').textContent()!=='22.5°')throw Error('Next angle failed');
  await page.locator('#prev').click();
  if(await page.locator('#angle').textContent()!=='0°')throw Error('Previous angle failed');
  await page.locator('.angle').nth(8).click();
  if(!(await page.locator('#hero').getAttribute('src')).includes('180.0'))throw Error('Contact selection failed');
  await page.locator('#play').click();
  await page.waitForFunction(()=>document.getElementById('angle').value!=='180°');
  await page.locator('#play').click();
  if(await page.locator('#play').textContent()!=='Play rotation')throw Error('Pause failed');
  await page.locator('.angle').nth(2).click();
  await page.screenshot({path:path.join(__dirname,'review-page.png'),fullPage:true});
  await page.goto(url+'?sheet=1');
  await page.waitForFunction(()=>[...document.images].every(i=>i.complete && i.naturalWidth>0));
  await page.locator('#sheet').screenshot({path:path.join(__dirname,'all-16-angles.png')});
  if(errors.length)throw Error(errors.join('\n'));
  fs.writeFileSync(path.join(__dirname,'review-ui-check.json'),JSON.stringify({passed:true,checks:['all reference and render images load','next/previous exact angle','contact-sheet selection','play/pause','16-view contact sheet rendered'],pageErrors:errors},null,2));
  await browser.close();console.log('REVIEW_UI_PASS');
})().catch(e=>{console.error(e);process.exit(1)});
